-- ---------------------------------------------------------
-- TB_EMPRESA
-- ---------------------------------------------------------
CREATE TABLE TB_EMPRESA (
    ID_EMPRESA              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NM_EMPRESA              VARCHAR2(150)   NOT NULL,
    NR_CNPJ                 VARCHAR2(18)    NOT NULL,
    DS_SETOR                VARCHAR2(100)   NOT NULL,
    DS_EMAIL_RESPONSAVEL    VARCHAR2(150)   NOT NULL,
    DT_CRIACAO              TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_EMPRESA PRIMARY KEY (ID_EMPRESA),
    CONSTRAINT UK_EMPRESA_CNPJ UNIQUE (NR_CNPJ)
);

-- ---------------------------------------------------------
-- TB_USUARIO
-- ---------------------------------------------------------
CREATE TABLE TB_USUARIO (
    ID_USUARIO  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NM_USUARIO  VARCHAR2(150)   NOT NULL,
    DS_EMAIL    VARCHAR2(150)   NOT NULL,
    DS_SENHA    VARCHAR2(255)   NOT NULL,
    DS_ROLE     VARCHAR2(10)    NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT CK_USUARIO_ROLE CHECK (DS_ROLE IN ('ADMIN', 'USER'))
);

-- IX implícito: UK_USUARIO_EMAIL cria um índice B-tree único em DS_EMAIL no Oracle,
-- cobrindo as consultas por e-mail do UserDetailsService sem índice adicional.

-- ---------------------------------------------------------
-- TB_LICENCA_AMBIENTAL
-- ---------------------------------------------------------
CREATE TABLE TB_LICENCA_AMBIENTAL (
    ID_LICENCA          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_EMPRESA          NUMBER(19)      NOT NULL,
    DS_TIPO_LICENCA     VARCHAR2(100)   NOT NULL,
    NR_LICENCA          VARCHAR2(50)    NOT NULL,
    DT_EMISSAO          DATE            NOT NULL,
    DT_VALIDADE         DATE            NOT NULL,
    DS_STATUS           VARCHAR2(20)    NOT NULL,
    DS_ORGAO_EMISSOR    VARCHAR2(100)   NOT NULL,
    CONSTRAINT PK_LICENCA PRIMARY KEY (ID_LICENCA),
    CONSTRAINT UK_LICENCA_NUMERO UNIQUE (NR_LICENCA),
    CONSTRAINT FK_LICENCA_EMPRESA FOREIGN KEY (ID_EMPRESA)
        REFERENCES TB_EMPRESA (ID_EMPRESA),
    CONSTRAINT CK_LICENCA_STATUS CHECK (DS_STATUS IN ('ATIVA', 'VENCIDA', 'SUSPENSA', 'CANCELADA'))
);

CREATE INDEX IX_LICENCA_EMPRESA ON TB_LICENCA_AMBIENTAL (ID_EMPRESA);
CREATE INDEX IX_LICENCA_VALIDADE ON TB_LICENCA_AMBIENTAL (DT_VALIDADE);

-- ---------------------------------------------------------
-- TB_AUDITORIA_AMBIENTAL
-- ---------------------------------------------------------
CREATE TABLE TB_AUDITORIA_AMBIENTAL (
    ID_AUDITORIA    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_EMPRESA      NUMBER(19)      NOT NULL,
    DT_AUDITORIA    DATE            NOT NULL,
    DS_RESULTADO    VARCHAR2(200)   NOT NULL,
    DS_OBSERVACOES  VARCHAR2(1000),
    DS_NIVEL_RISCO  VARCHAR2(10)    NOT NULL,
    CONSTRAINT PK_AUDITORIA PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT FK_AUDITORIA_EMPRESA FOREIGN KEY (ID_EMPRESA)
        REFERENCES TB_EMPRESA (ID_EMPRESA),
    CONSTRAINT CK_AUDITORIA_RISCO CHECK (DS_NIVEL_RISCO IN ('BAIXO', 'MEDIO', 'ALTO'))
);

CREATE INDEX IX_AUDITORIA_EMPRESA ON TB_AUDITORIA_AMBIENTAL (ID_EMPRESA);

-- ---------------------------------------------------------
-- TB_EMISSAO_CARBONO
-- ---------------------------------------------------------
CREATE TABLE TB_EMISSAO_CARBONO (
    ID_EMISSAO          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_EMPRESA          NUMBER(19)      NOT NULL,
    VL_QUANTIDADE_CO2   NUMBER(15,4)    NOT NULL,
    DS_FONTE_EMISSAO    VARCHAR2(150)   NOT NULL,
    DT_REGISTRO         DATE            NOT NULL,
    DS_UNIDADE_MEDIDA   VARCHAR2(20)    NOT NULL,
    CONSTRAINT PK_EMISSAO PRIMARY KEY (ID_EMISSAO),
    CONSTRAINT FK_EMISSAO_EMPRESA FOREIGN KEY (ID_EMPRESA)
        REFERENCES TB_EMPRESA (ID_EMPRESA)
);

CREATE INDEX IX_EMISSAO_EMPRESA ON TB_EMISSAO_CARBONO (ID_EMPRESA);

-- ---------------------------------------------------------
-- TB_COMPENSACAO_AMBIENTAL
-- ---------------------------------------------------------
CREATE TABLE TB_COMPENSACAO_AMBIENTAL (
    ID_COMPENSACAO              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ID_EMPRESA                  NUMBER(19)      NOT NULL,
    DS_TIPO_COMPENSACAO         VARCHAR2(100)   NOT NULL,
    DS_DESCRICAO                VARCHAR2(500)   NOT NULL,
    VL_QUANTIDADE_COMPENSADA    NUMBER(15,4)    NOT NULL,
    DT_ACAO                     DATE            NOT NULL,
    CONSTRAINT PK_COMPENSACAO PRIMARY KEY (ID_COMPENSACAO),
    CONSTRAINT FK_COMPENSACAO_EMPRESA FOREIGN KEY (ID_EMPRESA)
        REFERENCES TB_EMPRESA (ID_EMPRESA)
);

CREATE INDEX IX_COMPENSACAO_EMPRESA ON TB_COMPENSACAO_AMBIENTAL (ID_EMPRESA);
